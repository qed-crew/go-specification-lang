// Package whyml translates a checked subset of Go with GPMA annotations to
// WhyML. It generates proof obligations; translation alone is not verification.
package whyml

import (
	"fmt"
	"go/ast"
	"go/parser"
	"go/token"
	"go/types"
	"strings"

	"gpma/framework/data"
)

type Options struct{ IntBits int }

func Translate(filename string, source []byte, options Options) (string, error) {
	fs := token.NewFileSet()
	file, err := parser.ParseFile(fs, filename, source, parser.ParseComments)
	if err != nil {
		return "", err
	}
	return Generate(data.NewASTData(file, fs, string(source)), options)
}

type binding struct {
	name, kind string
	param      bool
}
type generator struct {
	d                         *data.ASTData
	info                      *types.Info
	specs                     map[ast.Node][]clause
	functions                 map[*types.Func]*ast.FuncDecl
	names                     map[types.Object]string
	scopes                    []map[string]binding
	buf                       strings.Builder
	indent, serial, loopDepth int
	err                       error
	fn                        *ast.FuncDecl
	returnKind                string
	returnException           string
	min, max                  string
}

func Generate(d *data.ASTData, options Options) (string, error) {
	if d == nil || d.File == nil || d.FileSet == nil {
		return "", fmt.Errorf("whyml: missing Go AST")
	}
	if options.IntBits == 0 {
		options.IntBits = 64
	}
	if options.IntBits != 32 && options.IntBits != 64 {
		return "", fmt.Errorf("int_bits must be 32 or 64")
	}
	for _, decl := range d.File.Decls {
		if _, ok := decl.(*ast.FuncDecl); !ok {
			return "", fmt.Errorf("%s: only function declarations are supported (no imports, globals, or type declarations)", d.FileSet.Position(decl.Pos()))
		}
	}
	info := &types.Info{Types: map[ast.Expr]types.TypeAndValue{}, Defs: map[*ast.Ident]types.Object{}, Uses: map[*ast.Ident]types.Object{}}
	cfg := types.Config{Sizes: &types.StdSizes{WordSize: int64(options.IntBits / 8), MaxAlign: 8}}
	if _, err := cfg.Check(d.File.Name.Name, d.FileSet, []*ast.File{d.File}, info); err != nil {
		return "", fmt.Errorf("Go type check: %w", err)
	}
	specs, err := readSpecs(d.File, d.FileSet)
	if err != nil {
		return "", err
	}
	g := &generator{d: d, info: info, specs: specs, functions: map[*types.Func]*ast.FuncDecl{}, names: map[types.Object]string{}, min: "-9223372036854775808", max: "9223372036854775807"}
	if options.IntBits == 32 {
		g.min = "-2147483648"
		g.max = "2147483647"
	}
	for _, decl := range d.File.Decls {
		f := decl.(*ast.FuncDecl)
		if f.Recv != nil || f.Type.TypeParams != nil || f.Body == nil {
			g.fail(f, "methods, generics, and declarations without bodies are unsupported")
			break
		}
		if f.Name.Name == "init" || f.Name.Name == "_" {
			g.fail(f, "init and blank function declarations are unsupported")
			break
		}
		o := info.Defs[f.Name].(*types.Func)
		g.functions[o] = f
		g.names[o] = "go_" + f.Name.Name
	}
	// Emit callees first. Recursion needs separate termination and effect analysis.
	var ordered []*ast.FuncDecl
	state := map[*types.Func]int{}
	var visit func(*types.Func)
	visit = func(f *types.Func) {
		if state[f] == 2 || g.err != nil {
			return
		}
		if state[f] == 1 {
			g.fail(g.functions[f], "recursive calls are unsupported")
			return
		}
		state[f] = 1
		ast.Inspect(g.functions[f].Body, func(n ast.Node) bool {
			if c, ok := n.(*ast.CallExpr); ok {
				if id, ok := c.Fun.(*ast.Ident); ok {
					if callee, ok := info.Uses[id].(*types.Func); ok {
						if _, exists := g.functions[callee]; exists {
							visit(callee)
						}
					}
				}
			}
			return true
		})
		state[f] = 2
		ordered = append(ordered, g.functions[f])
	}
	for _, decl := range d.File.Decls {
		if f, ok := decl.(*ast.FuncDecl); ok {
			if o, ok := info.Defs[f.Name].(*types.Func); ok {
				visit(o)
			}
		}
	}
	if g.err != nil {
		return "", g.err
	}
	g.line("(* Generated by GPMA go2whyml; Go int width: %d. Prove every VC. *)", options.IntBits)
	g.line("module GoProgram")
	g.indent++
	for _, m := range []string{"int.Int", "ref.Ref", "array.Array", "array.IntArraySorted", "array.ArrayPermut"} {
		g.line("use %s", m)
	}
	g.line("predicate in_int (x:int) = %s <= x <= %s", g.min, g.max)
	g.line("predicate int_array (a:array int) = length a <= %s /\\ (forall k:int. 0 <= k < length a -> in_int a[k])", g.max)
	g.line("exception GoBreak")
	g.line("exception GoContinue")
	for _, f := range ordered {
		g.function(f)
	}
	g.indent--
	g.line("end")
	if g.err != nil {
		return "", g.err
	}
	return g.buf.String(), nil
}
func (g *generator) fail(n ast.Node, format string, args ...interface{}) {
	if g.err == nil {
		g.err = fmt.Errorf("%s: %s", g.d.FileSet.Position(n.Pos()), fmt.Sprintf(format, args...))
	}
}
func (g *generator) line(format string, args ...interface{}) {
	g.buf.WriteString(strings.Repeat("  ", g.indent))
	fmt.Fprintf(&g.buf, format, args...)
	g.buf.WriteByte('\n')
}
func (g *generator) fresh() string { g.serial++; return fmt.Sprintf("t_%d", g.serial) }
func (g *generator) push()         { g.scopes = append(g.scopes, map[string]binding{}) }
func (g *generator) pop()          { g.scopes = g.scopes[:len(g.scopes)-1] }
func (g *generator) lookup(name string) (binding, bool) {
	for i := len(g.scopes) - 1; i >= 0; i-- {
		if b, ok := g.scopes[i][name]; ok {
			return b, true
		}
	}
	return binding{}, false
}
func kind(t types.Type) string {
	switch t {
	case types.Typ[types.Int], types.Typ[types.UntypedInt]:
		return "int"
	case types.Typ[types.Bool], types.Typ[types.UntypedBool]:
		return "bool"
	}
	if s, ok := t.(*types.Slice); ok && s.Elem() == types.Typ[types.Int] {
		return "array int"
	}
	return ""
}
func (g *generator) declare(id *ast.Ident, param bool) binding {
	if !validIdent(id.Name) || id.Name == "max_int" || id.Name == "min_int" || id.Name == "true" || id.Name == "false" {
		g.fail(id, "identifier %q is unsupported or reserved by the specification language", id.Name)
	}
	o := g.info.Defs[id]
	k := kind(o.Type())
	if k == "" {
		g.fail(id, "unsupported type %s", o.Type())
	}
	n := g.fresh() + "_" + id.Name
	b := binding{n, k, param}
	g.names[o] = n
	g.scopes[len(g.scopes)-1][id.Name] = b
	return b
}
func (g *generator) function(f *ast.FuncDecl) {
	g.fn = f
	g.scopes = nil
	g.push()
	g.loopDepth = 0
	g.returnKind = "unit"
	if f.Type.Results != nil {
		if len(f.Type.Results.List) != 1 || len(f.Type.Results.List[0].Names) > 0 {
			g.fail(f, "only one unnamed scalar return value is supported")
			return
		}
		g.returnKind = kind(g.info.TypeOf(f.Type.Results.List[0].Type))
		if g.returnKind != "int" && g.returnKind != "bool" {
			g.fail(f, "only int/bool results are supported")
			return
		}
	}
	g.returnException = "GoReturn_" + f.Name.Name
	if g.returnKind == "unit" {
		g.line("exception %s", g.returnException)
	} else {
		g.line("exception %s %s", g.returnException, g.returnKind)
	}
	var params []binding
	var signature []string
	arrays := 0
	for _, field := range f.Type.Params.List {
		if len(field.Names) == 0 {
			g.fail(field, "parameters must be named")
			return
		}
		for _, id := range field.Names {
			if id.Name == "_" {
				g.fail(id, "blank parameters are unsupported")
				return
			}
			b := g.declare(id, true)
			params = append(params, b)
			signature = append(signature, fmt.Sprintf("(%s: %s)", b.name, b.kind))
			if b.kind == "array int" {
				arrays++
			}
		}
	}
	if arrays > 1 {
		g.fail(f, "at most one []int parameter is supported; overlapping slices require an alias model")
		return
	}
	if len(signature) == 0 {
		signature = append(signature, "()")
	}
	g.line("let %s %s : %s", g.names[g.info.Defs[f.Name]], strings.Join(signature, " "), g.returnKind)
	g.indent++
	for _, p := range params {
		if p.kind == "int" {
			g.line("requires { in_int %s }", p.name)
		}
		if p.kind == "array int" {
			g.line("requires { int_array %s }", p.name)
			g.line("ensures { int_array %s }", p.name)
		}
	}
	for _, c := range g.specs[f] {
		g.line("%s { %s }", c.kind, g.logic(c.expr, c.kind == "ensures", false, nil))
	}
	if g.returnKind == "int" {
		g.line("ensures { in_int result }")
	}
	g.line("= try")
	g.indent++
	g.statements(f.Body.List)
	if g.returnKind == "unit" {
		g.line("()")
	} else {
		g.line("absurd")
	}
	g.indent--
	if g.returnKind == "unit" {
		g.line("with %s -> () end", g.returnException)
	} else {
		g.line("with %s result -> result end", g.returnException)
	}
	g.indent--
	g.pop()
}
